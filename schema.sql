CREATE TABLE IF NOT EXISTS pickup_requests (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    reference VARCHAR(17) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    request_key CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    customer_name VARCHAR(100) NOT NULL,
    phone VARCHAR(16) NOT NULL,
    pickup_address VARCHAR(500) NOT NULL,
    service ENUM('wash-fold', 'ironing', 'bedding') NOT NULL,
    estimated_weight DECIMAL(4,1) NOT NULL,
    preferred_date DATE NOT NULL,
    preferred_time ENUM('morning', 'afternoon', 'late-afternoon') NOT NULL,
    instructions VARCHAR(1000) NOT NULL DEFAULT '',
    sample_rate DECIMAL(7,2) NOT NULL,
    estimated_total DECIMAL(10,2) NOT NULL,
    status ENUM('requested', 'contacted', 'scheduled', 'completed', 'cancelled') NOT NULL DEFAULT 'requested',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_reference (reference),
    UNIQUE KEY uq_request_key (request_key),
    KEY ix_preferred_date (preferred_date),
    CONSTRAINT chk_weight CHECK (estimated_weight BETWEEN 0.5 AND 100.0),
    CONSTRAINT chk_rate CHECK (sample_rate > 0),
    CONSTRAINT chk_total CHECK (estimated_total >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
